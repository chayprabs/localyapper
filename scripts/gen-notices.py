#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md (plan P7.8).

Usage: python3 scripts/gen-notices.py [OUT]

The models, runtimes and test fixtures are listed by hand; the Rust crates
come from `cargo metadata` (every package in Cargo.lock, all platforms)
and the npm packages from the production dependency tree (`npm ls
--omit=dev`). Run it after changing dependencies; the release workflow
runs it before bundling.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEADER = """# Third-party notices

LocalYapper is MIT-licensed. It ships or downloads the following
third-party components. This file is generated by
`scripts/gen-notices.py`.

## Models and runtimes

| Component | Use | Licence | Source |
|---|---|---|---|
| NVIDIA Parakeet TDT-CTC 110M and Parakeet TDT 0.6B v3 (sherpa-onnx exports) | Speech recognition, downloaded on first use | CC-BY-4.0 | https://huggingface.co/nvidia, https://github.com/k2-fsa/sherpa-onnx |
| Moonshine Tiny (English) | Speech recognition for low-RAM machines, downloaded on demand | MIT | https://github.com/usefulsensors/moonshine |
| Silero VAD | Voice activity detection, bundled as `resources/silero_vad.onnx` | MIT | https://github.com/snakers4/silero-vad |
| sherpa-onnx | Speech recognition runtime, linked into the app | Apache-2.0 | https://github.com/k2-fsa/sherpa-onnx |
| ONNX Runtime | Neural network runtime used by sherpa-onnx | MIT | https://github.com/microsoft/onnxruntime |

Parakeet models are © NVIDIA, licensed under CC-BY-4.0
(https://creativecommons.org/licenses/by/4.0/). The app downloads them
unchanged from the sherpa-onnx model releases and verifies their SHA-256.

## Test fixtures

The audio clips in `src-tauri/tests/fixtures` (not shipped in the app)
are from LibriSpeech (Panayotov et al.), CC-BY-4.0,
https://www.openslr.org/12/.
"""


def rust_crates():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--manifest-path", str(ROOT / "src-tauri" / "Cargo.toml")],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    meta = json.loads(out)
    rows = set()
    for p in meta["packages"]:
        if p["name"] == "localyapper":
            continue
        rows.add((p["name"], p["version"], p.get("license") or "see crate", p.get("repository") or ""))
    return sorted(rows)


def npm_packages():
    out = subprocess.run(
        ["npm", "ls", "--omit=dev", "--all", "--json", "--long"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    ).stdout
    tree = json.loads(out or "{}")
    rows = set()

    def walk(deps):
        for name, info in (deps or {}).items():
            # Optional peers of a runtime package that only the build
            # tools install (e.g. jotai's @babel/core) are not shipped.
            if info.get("dev") or info.get("devOptional") or info.get("peer"):
                continue
            lic = info.get("license") or "see package"
            if isinstance(lic, dict):
                lic = lic.get("type", "see package")
            rows.add((name, info.get("version", "?"), lic))
            walk(info.get("dependencies"))

    walk(tree.get("dependencies"))
    return sorted(rows)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "THIRD_PARTY_NOTICES.md"
    lines = [HEADER, "## Rust crates", "", "| Crate | Version | Licence |", "|---|---|---|"]
    for name, version, lic, _repo in rust_crates():
        lines.append(f"| {name} | {version} | {lic} |")
    lines += ["", "## npm packages (shipped in the app's web pages)", "", "| Package | Version | Licence |", "|---|---|---|"]
    for name, version, lic in npm_packages():
        lines.append(f"| {name} | {version} | {lic} |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
