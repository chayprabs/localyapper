#!/usr/bin/env python3
"""Turn bench harness output files into docs/MODEL_BENCHMARK.md.

Usage: write-benchmark.py <results_dir> <out.md>
Each results file is the stdout of one `bench` run.
"""
import glob
import os
import platform
import sys

results, out = sys.argv[1], sys.argv[2]
summaries, details = [], []
for path in sorted(glob.glob(os.path.join(results, "*.txt"))):
    lines = open(path, encoding="utf-8").read().splitlines()
    for line in lines:
        if line.startswith("SUMMARY |"):
            f = [p.strip() for p in line.split("|")[1:]]
            kv = dict(p.split(" ", 1) for p in f[1:])
            summaries.append((f[0], kv))
    details.append((os.path.basename(path), [l for l in lines if l.startswith("|")]))

cpu = "unknown"
try:
    for line in open("/proc/cpuinfo"):
        if line.startswith("model name"):
            cpu = line.split(":", 1)[1].strip()
            break
except OSError:
    pass

md = ["# Model benchmark", "",
      "Generated by `.github/workflows/bench.yml` with `src-tauri/examples/bench.rs`",
      "on the GitHub Linux runner. Do not edit by hand.", "",
      f"Runner: {platform.platform()}, {os.cpu_count()} logical CPUs, {cpu}.", "",
      "Fixtures: `src-tauri/tests/fixtures` (LibriSpeech test-clean, CC-BY-4.0).", "",
      "| Model | Threads | Load ms | Warm-up ms | RTF | Peak RSS MB | WER % |",
      "|---|---|---|---|---|---|---|"]
for model, kv in summaries:
    md.append(f"| {model} | {kv['threads']} | {kv['load_ms']} | {kv['warmup_ms']} | "
              f"{kv['rtf']} | {kv['peak_rss_mb']} | {kv['wer_pct']} |")
md += ["", "RTF is decode time divided by audio time (lower is faster). A model whose",
       "RTF on 4 threads is above 0.3 is dropped from the catalog (plan section 9.1).", ""]
for name, rows in details:
    md += [f"## {name}", ""] + rows + [""]
open(out, "w", encoding="utf-8").write("\n".join(md))
print("\n".join(md[:20]))
